"use client";

import { useEffect, useRef, useState } from "react";
import { Circle, Copy, Download, Sparkles, Square, Upload } from "lucide-react";
import { cn } from "@/lib/cn";
import { SmallButton, ViewHeader } from "./ui";

const journey = [
  "Open the Loan Application screen",
  "Enter customer number",
  "Select loan sub-product",
  "Enter amount and term",
  "Submit the application",
  "Wait on the confirmation screen",
];

const script = `# Generated by TestNova Studio
def run(page, data):
    page.goto(data["url"])
    page.fill("#customer", data["CustomerId"])
    page.select("#sub-product", data["ProductCode"])
    page.fill("#amount", data["TotalCost"])
    page.fill("#term", data["Term"])
    page.click("#submit")
    page.wait_for("#confirmation")`;

type Phase = "idle" | "recording" | "recorded" | "generated";

export function StudioView({ toast }: { toast: (m: string) => void }) {
  const [phase, setPhase] = useState<Phase>("idle");
  const [actions, setActions] = useState(0);
  const timer = useRef<ReturnType<typeof setInterval> | null>(null);

  useEffect(() => () => { if (timer.current) clearInterval(timer.current); }, []);

  const start = () => {
    setActions(0);
    setPhase("recording");
    timer.current = setInterval(() => {
      setActions((a) => {
        if (a + 1 >= journey.length && timer.current) clearInterval(timer.current);
        return Math.min(a + 1, journey.length);
      });
    }, 650);
  };
  const stop = () => {
    if (timer.current) clearInterval(timer.current);
    setPhase("recorded");
  };

  return (
    <>
      <ViewHeader
        title="TestNova Studio"
        tour={[
          { title: "TestNova Studio", body: "Create automated scenarios by recording your actions in a browser — no scripting required." },
          { title: "Capture → Generate → Review → Save", body: "A companion browser extension records the journey; Studio converts it into a scenario script you can review, then Copy, Download or Upload / Create Scenario." },
        ]}
      />

      <ol className="mb-3 flex flex-wrap gap-2 text-[10px] font-semibold">
        {[
          ["Capture", phase !== "idle"],
          ["Generate", phase === "generated"],
          ["Review", phase === "generated"],
          ["Save", false],
        ].map(([l, done], i) => (
          <li key={String(l)} className={cn("flex items-center gap-1.5 rounded-full border px-2.5 py-1", done ? "border-accent bg-accent/10 text-accent" : "border-border-warm text-muted-foreground")}>
            <span className="font-heading">{i + 1}</span>{l}
          </li>
        ))}
      </ol>

      <div className="grid gap-3 md:grid-cols-2">
        <div className="rounded-xl border border-border-warm bg-white p-3.5">
          <div className="flex items-center justify-between">
            <p className="text-xs font-bold text-foreground">Recorder</p>
            <span className="flex items-center gap-1.5 text-[10px] text-muted-foreground">
              {phase === "recording" && <Circle className="size-2.5 animate-pulse fill-red-500 text-red-500" aria-hidden="true" />}
              {actions} actions
            </span>
          </div>
          <ul className="mt-2 flex min-h-36 flex-col gap-1.5">
            {journey.slice(0, actions).map((j, i) => (
              <li key={j} className="flex items-center gap-2 rounded-lg bg-background px-2.5 py-1.5 text-[11px] text-foreground">
                <span className="font-mono text-[10px] text-accent">{String(i + 1).padStart(2, "0")}</span>{j}
              </li>
            ))}
            {actions === 0 && <li className="py-6 text-center text-[11px] text-muted-foreground">Nothing recorded yet. Anything done before you start isn&apos;t captured.</li>}
          </ul>
          <div className="mt-3 flex gap-2">
            {phase === "recording" ? (
              <SmallButton variant="danger" onClick={stop}><Square className="size-3" aria-hidden="true" /> Stop</SmallButton>
            ) : (
              <SmallButton onClick={start}><Circle className="size-3 fill-current" aria-hidden="true" /> {phase === "idle" ? "Start recording" : "Record again"}</SmallButton>
            )}
            <SmallButton variant="ghost" disabled={phase !== "recorded"} onClick={() => setPhase("generated")}>
              <Sparkles className="size-3.5" aria-hidden="true" /> Generate
            </SmallButton>
          </div>
        </div>

        <div className="rounded-xl border border-border-warm bg-white p-3.5">
          <p className="text-xs font-bold text-foreground">Script preview</p>
          {phase === "generated" ? (
            <>
              <pre className="mt-2 max-h-44 overflow-auto rounded-lg bg-[#1f1b16] p-3 font-mono text-[10px] leading-relaxed text-[#f3ead9]">{script}</pre>
              <div className="mt-3 flex flex-wrap gap-2">
                <SmallButton variant="ghost" onClick={() => toast("Script copied")}><Copy className="size-3" aria-hidden="true" /> Copy</SmallButton>
                <SmallButton variant="ghost" onClick={() => toast("Script downloaded")}><Download className="size-3" aria-hidden="true" /> Download</SmallButton>
                <SmallButton onClick={() => toast("Scenario created in the selected folder")}><Upload className="size-3" aria-hidden="true" /> Upload / Create Scenario</SmallButton>
              </div>
              <p className="mt-2 text-[10px] text-muted-foreground">Review generated scripts before introducing them into maintained scenario content.</p>
            </>
          ) : (
            <p className="py-14 text-center text-[11px] text-muted-foreground">Record a journey, stop, then Generate to see the scenario script.</p>
          )}
        </div>
      </div>
    </>
  );
}
